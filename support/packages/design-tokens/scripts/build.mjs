// Core tokens (DTCG JSON) and themes → CSS variables, a Tailwind v4 theme, Dart, and the API's copy of the themes.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";
import { DEFAULT, derive, stylesheet } from "../src/theme.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(root, "dist");
const dart = resolve(root, "dart/lib");
for (const dir of [out, dart]) mkdirSync(dir, { recursive: true });
const BANNER = "Generated by support/packages/design-tokens. Do not edit.";

async function load(file) {
  const sd = new StyleDictionary({
    source: [resolve(root, "src", file)],
    platforms: { raw: { transforms: ["name/kebab"] } },
    log: { verbosity: "silent" },
  });
  return (await sd.getPlatformTokens("raw")).allTokens;
}

const core = await load("core.json");
const light = derive(DEFAULT.theme, "light", DEFAULT.color);
const dark = derive(DEFAULT.theme, "dark", DEFAULT.color);
const family = (v) =>
  [v]
    .flat()
    .map((f) => (/\s/.test(f) ? `"${f}"` : f))
    .join(", ");
const css = (t) => {
  if (t.$type === "cubicBezier") return `cubic-bezier(${t.$value.join(", ")})`;
  return t.$type === "fontFamily" ? family(t.$value) : t.$value;
};
const of = (group) => core.filter((t) => t.path[0] === group);
const type = of("type");
const simple = core.filter((t) => t.$type !== "typography");
const vars = (tokens, pad = "  ") => tokens.map((t) => `${pad}--${t.name}: ${css(t)};`).join("\n");
const rem = (px) => `${Number.parseFloat(px) / 16}rem`; // text scales with the reader's font size

writeFileSync(
  resolve(out, "tokens.css"),
  `/* ${BANNER} The colours are the bundled default; the published theme outranks them. */
:root {
${vars(simple.filter((t) => t.path[0] !== "font" && t.path[0] !== "radius" && t.path[0] !== "ease"))}
}
${stylesheet(light, dark, ":root")}@media (prefers-reduced-motion: reduce) {
  :root {
    --duration-fast: 0ms;
    --duration-base: 0ms;
    --duration-slow: 0ms;
  }
}
`,
);

writeFileSync(
  resolve(out, "theme.css"),
  `/* ${BANNER} */
@theme {
  --font-*: initial;
  --radius-*: initial;
  --text-*: initial;
  --spacing: 4px;
${vars([...of("font"), ...of("radius"), ...of("ease")])}
${type
  .map(({ path, $value: v }) => {
    const n = `--text-${path[1]}`;
    return `  ${n}: ${rem(v.fontSize)};\n  ${n}--line-height: ${rem(v.lineHeight)};\n  ${n}--font-weight: ${v.fontWeight};`;
  })
  .join("\n")}
}
@theme inline {
  --color-*: initial;
  /* Over pictures, video and the page behind a dialog: the same in both themes. */
  --color-black: #000;
  --color-white: #fff;
${Object.keys(light)
  .map((k) => `  --color-${k}: var(--color-${k});`)
  .join("\n")}
}
`,
);

const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const names = Object.keys(light).map(camel);
const px = (v) => Number.parseFloat(v).toFixed(1);
const lines = (items, fn) => items.map(fn).join("\n");
const palette = (label, tokens) =>
  `  static const ${label} = NewsColors(\n${lines(Object.entries(tokens), ([k, v]) => `    ${camel(k)}: Color(0xFF${v.slice(1).toUpperCase()}),`)}\n  );`;
writeFileSync(
  resolve(dart, "news_design_tokens.dart"),
  `// ${BANNER}
import 'package:material_ui/material_ui.dart';

export 'theme_derivation.dart';

/// Every colour a widget may use. Built from the published theme; [light] and [dark] are the bundled default.
@immutable
class NewsColors extends ThemeExtension<NewsColors> {
  const NewsColors({
${lines(names, (n) => `    required this.${n},`)}
  });

${lines(names, (n) => `  final Color ${n};`)}

${palette("light", light)}

${palette("dark", dark)}

  /// From derived tokens, by their shared names. A missing name is a bug, so it throws.
  factory NewsColors.fromTokens(Map<String, String> tokens) {
    Color c(String name) => Color(0xFF000000 | int.parse(tokens[name]!.substring(1), radix: 16));
    return NewsColors(
${lines(Object.keys(light), (k) => `      ${camel(k)}: c('${k}'),`)}
    );
  }

  @override
  NewsColors copyWith({
${lines(names, (n) => `    Color? ${n},`)}
  }) {
    return NewsColors(
${lines(names, (n) => `      ${n}: ${n} ?? this.${n},`)}
    );
  }

  @override
  NewsColors lerp(NewsColors? other, double t) {
    if (other == null) return this;
    return NewsColors(
${lines(names, (n) => `      ${n}: Color.lerp(${n}, other.${n}, t)!,`)}
    );
  }
}

abstract final class NewsSpace {
${lines(of("space"), (t) => `  static const double s${t.path[1]} = ${px(t.$value)};`)}
}

abstract final class NewsRadius {
${lines(of("radius"), (t) => `  static const double ${t.path[1]} = ${px(t.$value)};`)}
}

abstract final class NewsMotion {
${lines(of("duration"), (t) => `  static const Duration ${t.path[1]} = Duration(milliseconds: ${Number.parseInt(t.$value, 10)});`)}
  static const Curve standard = Cubic(${of("ease")[0].$value.join(", ")});
}

abstract final class NewsType {
${lines(type, ({ path, $value: v }) => `  static const TextStyle ${camel(path[1])} = TextStyle(\n    fontFamily: '${v.fontFamily[0].replace(" Variable", "")}',\n    fontSize: ${px(v.fontSize)},\n    height: ${Number.parseFloat(v.lineHeight)} / ${Number.parseFloat(v.fontSize)},\n    fontWeight: FontWeight.w${v.fontWeight},\n  );`)}
}
`,
);
const themes = readFileSync(resolve(root, "src/themes.json"), "utf8");
writeFileSync(
  resolve(dart, "theme_spec.g.dart"),
  `// ${BANNER}\n/// src/themes.json, as it is.\nconst themeSpecJson = r'''\n${themes}''';\n`,
);
const api = resolve(root, "../../../backend/newsplatform/site_config/theme");
if (existsSync(api)) copyFileSync(resolve(root, "src/themes.json"), `${api}/themes.json`); // not in the console's image
writeFileSync(
  resolve(root, "dart/pubspec.yaml"),
  `# ${BANNER}\nname: news_design_tokens\npublish_to: none\nversion: 0.1.0\nenvironment:\n  sdk: ^3.14.0\n  flutter: ">=3.50.0"\ndependencies:\n  flutter:\n    sdk: flutter\n  material_ui: ^1.11.1\ndev_dependencies:\n  flutter_test:\n    sdk: flutter\n`,
);
