// One JSON Schema → TypeScript types, Zod validators, Dart models, and the copy the API validates against.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const source = readFileSync(`${root}/schema/content.v1.json`, "utf8");
const schema = JSON.parse(source);
const defs = { ...schema.$defs, document: { ...schema, $defs: undefined } };
const BANNER = "// Generated by support/packages/content-schema. Do not edit.\n";
const pascal = (s) => s.replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase());
const camel = (s) => s.replace(/_(\w)/g, (_, c) => c.toUpperCase());
const refName = (node) => node.$ref?.split("/").at(-1);
const title = (name) => defs[name].title ?? pascal(name);
const isScalar = (name) => !["object", "oneOf"].includes(defs[name].oneOf ? "oneOf" : defs[name].type);
const write = (path, text) => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
};
const props = (node) =>
  Object.entries(node.properties).map(([name, spec]) => ({
    name,
    spec,
    required: node.required.includes(name),
  }));
const tags = (name) => {
  const t = defs[name].properties.type;
  return t.enum ?? [t.const];
};
// Dependencies first: Zod needs a schema before it is used.
const order = [];
const visit = (name) => {
  if (order.includes(name)) return;
  for (const m of JSON.stringify(defs[name]).matchAll(/#\/\$defs\/(\w+)/g)) visit(m[1]);
  order.push(name);
};
visit("document");

// ---- TypeScript -------------------------------------------------------------------------------------------
function ts(node) {
  const ref = refName(node);
  if (ref) return isScalar(ref) ? "string" : title(ref);
  if (node.const !== undefined) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (node.type === "array") return `${ts(node.items)}[]`;
  return { string: "string", integer: "number", boolean: "boolean" }[node.type];
}
function zod(node) {
  const ref = refName(node);
  if (ref) return camel(ref);
  if (node.const !== undefined) return `z.literal(${JSON.stringify(node.const)})`;
  if (node.enum) return `z.enum(${JSON.stringify(node.enum)})`;
  if (node.type === "array") return `z.array(${zod(node.items)}).min(${node.minItems}).max(${node.maxItems})`;
  if (node.type === "boolean") return "z.boolean()";
  if (node.type === "integer") return `z.int().min(${node.minimum}).max(${node.maximum})`;
  let out = "z.string()";
  // JSON Schema counts characters, JavaScript counts UTF-16 units.
  if (node.minLength) out += `.min(${node.minLength})`;
  if (node.maxLength) out += `.refine((s) => [...s].length <= ${node.maxLength}, "too long")`;
  if (node.pattern) out += `.regex(new RegExp(${JSON.stringify(node.pattern)}, "u"))`;
  return out;
}
let types = BANNER;
let validators = `${BANNER}import { z } from "zod";\n\n/** Writers are strict; readers ignore fields a newer server added. */\nfunction build(object: typeof z.strictObject) {\n`;
for (const name of order) {
  const node = defs[name];
  if (node.oneOf) {
    const members = node.oneOf.map(refName);
    types += `export type ${title(name)} =\n${members.map((m) => `  | ${title(m)}`).join("\n")};\n`;
    validators += `  const ${camel(name)} = z.discriminatedUnion("type", [${members.map(camel).join(", ")}]);\n`;
  } else if (node.type === "object") {
    types += `export type ${title(name)} = {\n${props(node)
      .map((p) => `  ${p.name}${p.required ? "" : "?"}: ${ts(p.spec)};`)
      .join("\n")}\n};\n`;
    validators += `  const ${camel(name)} = object({\n${props(node)
      .map((p) => `    ${p.name}: ${zod(p.spec)}${p.required ? "" : ".optional()"},`)
      .join("\n")}\n  });\n`;
  } else validators += `  const ${camel(name)} = ${zod(node)};\n`;
}
validators += `  return { document, block };\n}\nexport const strict = build(z.strictObject);\nexport const lenient = build(z.object as unknown as typeof z.strictObject);\n`;
types += `export const BLOCK_TYPES = ${JSON.stringify(defs.block.oneOf.flatMap((r) => tags(refName(r))))} as const;\n`;
write(`${root}/src/generated/types.ts`, types);
write(`${root}/src/generated/validators.ts`, validators);

// ---- Dart -------------------------------------------------------------------------------------------------
const enums = new Map();
const enumName = (owner, prop) => pascal(`${owner.replace(/Block$/, "")}_${prop}`);
function dartType(node, owner, prop) {
  const ref = refName(node);
  if (ref) return isScalar(ref) ? "String" : title(ref);
  if (node.enum) {
    const name = prop === "type" ? `${owner}Type` : enumName(owner, prop);
    enums.set(name, node.enum);
    return name;
  }
  if (node.type === "array") return `List<${dartType(node.items, owner, prop)}>`;
  return { string: "String", integer: "int", boolean: "bool" }[node.type];
}
function decode(node, expr, owner, prop) {
  const ref = refName(node);
  if (ref)
    return isScalar(ref) ? `${expr} as String` : `${title(ref)}.fromJson(${expr} as Map<String, dynamic>)`;
  if (node.enum) return `${dartType(node, owner, prop)}.parse(${expr} as String)`;
  if (node.type === "array") {
    const item = decode(node.items, "e", owner, prop);
    return `List.unmodifiable((${expr} as List<dynamic>).map((e) => ${item}))`;
  }
  return `${expr} as ${dartType(node, owner, prop)}`;
}
function encode(node, expr) {
  const ref = refName(node);
  if (ref) return isScalar(ref) ? expr : `${expr}.toJson()`;
  if (node.enum) return `${expr}.value`;
  if (node.type === "array")
    return refName(node.items) && isScalar(refName(node.items))
      ? expr
      : `${expr}.map((e) => ${encode(node.items, "e")}).toList()`;
  return expr;
}
// A fallback keeps one unknown node from losing the whole article.
const UNKNOWN = {
  Block: "UnknownBlock",
  LiveBlock: "UnknownBlock",
  Inline: "UnknownInline",
  Mark: "UnknownMark",
};
const parents = {};
function addParent(child, parent) {
  parents[child] = [...(parents[child] ?? []), parent];
}
for (const name of order)
  if (defs[name].oneOf) for (const r of defs[name].oneOf) addParent(refName(r), title(name));
const dart = `${BANNER.replace("//", "//")}// ignore_for_file: sort_constructors_first\nlibrary;\n\n`;
let body = "";
for (const name of order) {
  const node = defs[name];
  const cls = title(name);
  if (node.oneOf) {
    const unknown = UNKNOWN[cls];
    const cases = node.oneOf
      .map(refName)
      .map(
        (m) =>
          `        ${tags(m)
            .map((t) => `'${t}'`)
            .join(" || ")} => ${title(m)}.fromJson(json),`,
      )
      .join("\n");
    body += `sealed class ${cls} {\n  Map<String, dynamic> toJson();\n\n  /// Never throws: anything unknown or malformed becomes [${unknown}].\n  static ${cls} fromJson(Map<String, dynamic> json) {\n    try {\n      return switch (json['type']) {\n${cases}\n        _ => ${unknown}(json),\n      };\n    } on Object {\n      return ${unknown}(json);\n    }\n  }\n}\n\n`;
    continue;
  }
  if (node.type !== "object") continue;
  const fields = props(node).filter((p) => p.spec.const === undefined);
  const fixed = props(node).filter((p) => p.spec.const !== undefined);
  const impl = parents[name] ? ` implements ${parents[name].join(", ")}` : "";
  body += `final class ${cls}${impl} {\n`;
  body += `  const ${cls}(${fields.length ? `{${fields.map((p) => `${p.required ? "required " : ""}this.${p.name}`).join(", ")}}` : ""});\n`;
  for (const p of fields)
    body += `  final ${dartType(p.spec, cls, p.name)}${p.required ? "" : "?"} ${p.name};\n`;
  body += `\n  factory ${cls}.fromJson(Map<String, dynamic> json) => ${fields.length ? "" : "const "}${cls}(${fields
    .map(
      (p) =>
        `${p.name}: ${p.required ? decode(p.spec, `json['${p.name}']`, cls, p.name) : `json['${p.name}'] == null ? null : ${decode(p.spec, `json['${p.name}']`, cls, p.name)}`}`,
    )
    .join(", ")});\n`;
  body += `\n  ${parents[name] ? "@override\n  " : ""}Map<String, dynamic> toJson() => {${[
    ...fixed.map(
      (p) => `'${p.name}': ${typeof p.spec.const === "string" ? `'${p.spec.const}'` : p.spec.const}`,
    ),
    ...fields.map((p) =>
      p.required
        ? `'${p.name}': ${encode(p.spec, p.name)}`
        : `if (${p.name} case final v?) '${p.name}': ${encode(p.spec, "v")}`,
    ),
  ].join(", ")}};\n}\n\n`;
}
body = body.replace(
  "\n  Map<String, dynamic> toJson() => {'version'",
  `
  /// For renderers: any input gives a document, never an exception.
  static ContentDocument read(Object? input) {
    final blocks = input is Map<String, dynamic> ? input['blocks'] : null;
    return ContentDocument(
      blocks: List.unmodifiable(
        (blocks is List<dynamic> ? blocks : const <dynamic>[]).map(
          (e) => e is Map<String, dynamic> ? Block.fromJson(e) : const UnknownBlock({}),
        ),
      ),
    );
  }

  Map<String, dynamic> toJson() => {'version'`,
);
for (const [cls, unionsOf] of [
  ["UnknownBlock", ["Block", "LiveBlock"]],
  ["UnknownInline", ["Inline"]],
  ["UnknownMark", ["Mark"]],
])
  body += `/// Written by a newer server. Renderers show a calm fallback, or nothing.\nfinal class ${cls} implements ${unionsOf.join(", ")} {\n  const ${cls}(this.raw);\n  final Map<String, dynamic> raw;\n\n  @override\n  Map<String, dynamic> toJson() => raw;\n}\n\n`;
for (const [name, values] of enums)
  body += `enum ${name} {\n${values.map((v) => `  ${v}('${v}')`).join(",\n")},\n  unknown('');\n\n  const ${name}(this.value);\n  final String value;\n\n  static ${name} parse(String raw) => values.firstWhere((e) => e.value == raw, orElse: () => unknown);\n}\n\n`;
write(`${root}/dart/lib/news_content.dart`, `${dart}${body.trimEnd()}\n`);

// ---- API --------------------------------------------------------------------------------------------------
write(resolve(root, "../../../backend/newsplatform/content/schema/content.v1.json"), source);
