// Every machine-written Swahili string, for a native editor. A reviewed string is recorded by its hash in
// support/docs/i18n/reviewed.json, so a later change asks for review again. CI fails when the list is stale.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../..", import.meta.url).pathname;
const read = (f) => JSON.parse(readFileSync(`${root}${f}`, "utf8"));
const flat = (o, at = "") =>
  Object.entries(o).flatMap(([k, v]) => (typeof v === "object" ? flat(v, `${at}${k}.`) : [[`${at}${k}`, v]]));
const reviewed = new Set(read("support/docs/i18n/reviewed.json"));
const en = Object.fromEntries(flat(read("admin/messages/en.json")));
const rows = flat(read("admin/messages/sw.json")).map(([key, sw]) => [
  "Admin console",
  key,
  sw,
  en[key] ?? "",
]);

// Themes, and the one number format that is a decision rather than a translation (ADR-0034).
const { themes } = read("support/packages/design-tokens/src/themes.json");
for (const [key, theme] of Object.entries(themes))
  for (const part of ["name", "note"])
    rows.push(["Themes", `themes.json ${key}.${part}`, theme[part].sw, theme[part].en]);
rows.push(["Themes", "compact counts (packages/ui news.tsx)", "1.3K · 3.4M · 1.2B", "1.3K · 3.4M · 1.2B"]);

// Pairs written in Python: field(…, en, sw), t.step(key, en, sw), Perm(key, en, sw), SystemRole(key, en, sw).
const found = execFileSync(
  "python3",
  ["-I", `${root}support/scripts/i18n_pairs.py`, `${root}backend/newsplatform`],
  {
    encoding: "utf8",
  },
);
rows.push(...JSON.parse(found).map(([key, e, sw]) => ["API", key, sw, e]));

const hash = (key, sw) => createHash("sha256").update(`${key}\0${sw}`).digest("hex").slice(0, 12);
const cell = (s) => s.replaceAll("|", "\\|").replaceAll("\n", " ");
const pending = rows.filter(([, key, sw]) => !reviewed.has(hash(key, sw)));
let out = `# Swahili review

Generated by \`node support/scripts/i18n-review.mjs\`. Do not edit.

The Swahili in this product was written by a machine and is **not final**. A native editor corrects the text at its source (\`admin/messages/sw.json\`, or the Python file named in the key), then adds the code to \`support/docs/i18n/reviewed.json\`. Reviewed strings leave this list and come back if they change.

**${pending.length} of ${rows.length} strings wait for review.**
`;
for (const part of ["Admin console", "Themes", "API"]) {
  out += `\n## ${part}\n\n| Code | Key | Swahili | English |\n|---|---|---|---|\n`;
  for (const [where, key, sw, e] of pending)
    if (where === part) out += `| ${hash(key, sw)} | ${key} | ${cell(sw)} | ${cell(e)} |\n`;
}
writeFileSync(`${root}support/docs/i18n/review.md`, out);
console.log(`${pending.length} of ${rows.length} strings wait for review`);
