import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("../..", import.meta.url).pathname;
const store = `${root}node_modules/.pnpm/`;
const dir = `${store}${readdirSync(store).find((d) => d.startsWith("lucide-react@"))}/node_modules/lucide-react/dist/esm/icons/`;
const NAMES =
  "house play compass bookmark circle-user heart share-2 search chevron-right chevron-left chevron-down arrow-right arrow-left arrow-up x check zap volume-2 volume-x pause images a-large-small clock trash-2 download wifi-off refresh-cw languages moon sun sun-moon info external-link file-text shield mail scale rotate-ccw ellipsis eye-off maximize minimize badge-check quote circle-alert triangle-alert circle-check link-2 gauge newspaper landmark trending-up trophy heart-pulse graduation-cap cpu music leaf globe earth message-square-quote history layers pen-line radio bell sparkles pin".split(
    " ",
  );
const n = Number;
const path = ([tag, a]) => {
  switch (tag) {
    case "path":
      return a.d;
    case "line":
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline":
      return `M${a.points.trim().split(/\s+/).join("L")}`;
    case "polygon":
      return `M${a.points.trim().split(/\s+/).join("L")}Z`;
    case "circle":
      return `M${n(a.cx) - n(a.r)} ${a.cy}a${a.r} ${a.r} 0 1 0 ${2 * a.r} 0a${a.r} ${a.r} 0 1 0 ${-2 * a.r} 0Z`;
    case "ellipse":
      return `M${n(a.cx) - n(a.rx)} ${a.cy}a${a.rx} ${a.ry} 0 1 0 ${2 * a.rx} 0a${a.rx} ${a.ry} 0 1 0 ${-2 * a.rx} 0Z`;
    case "rect": {
      const [x, y, w, h] = [a.x ?? 0, a.y ?? 0, a.width, a.height].map(n);
      const r = n(a.rx ?? a.ry ?? 0);
      return r
        ? `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${2 * r - w}a${r} ${r} 0 0 1 ${-r} ${-r}v${2 * r - h}a${r} ${r} 0 0 1 ${r} ${-r}Z`
        : `M${x} ${y}h${w}v${h}h${-w}Z`;
    }
  }
  throw new Error(tag);
};
const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
let out = `// Generated by support/scripts/mobile-icons.mjs from Lucide (ISC licence). Do not edit.\nimport 'news_icon.dart';\n\nabstract final class NewsIcons {\n`;
for (const name of NAMES) {
  let { __iconData } = await import(`${dir}${name}.mjs`);
  if (!__iconData) {
    const source = readFileSync(`${dir}${name}.mjs`, "utf8").match(/from ['"]\.\/([a-z0-9-]+)\.mjs/)[1]; // renamed
    ({ __iconData } = await import(`${dir}${source}.mjs`));
  }
  const list = __iconData.node.map(path).map((d) => `    '${d}',`);
  out += `  static const ${camel(name)} = NewsIconData([\n${list.join("\n")}\n  ]);\n`;
}
writeFileSync(`${root}mobile/lib/ui/tokens/news_icons.g.dart`, `${out}}\n`);
console.log(`${NAMES.length} icons`);
